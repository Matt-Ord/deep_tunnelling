"""HeSE hop rates of H and D on Ru(0001).

H_RATES, D_RATES: P. Townsend, PhD thesis (Cambridge, 2018), Sec. 6.3.

The rate is the inverse residence time 1 / tau in the metastable hcp hollow, i.e.
the escape rate out of hcp, in ps^-1 with its lower and upper bounds. It was
fitted with a non-Bravais fcc/hcp jump model (with multiple jumps) at 0.2 ML,
assuming a constant hcp-fcc site energy difference (H: fitted; D: 20 meV).
Extracted from the vector graphics of Fig. 6.13b (H, Delta K = 1.0 A^-1 along
<1,1>) and Fig. 6.15 (D, Delta K = 1.5 A^-1); temperatures are read from 1000 / T.
Repeated temperatures are separate measurements. The D bounds are the full width
at half maximum of the marginalized distribution of 1 / tau; below ~1e-5 ps^-1
polarization drift dominates (thesis Fig. 6.18).

The measured hcp-fcc site energy difference is 22 +- 1 meV (thesis Table 6.3 and
its Ref. 23).

MCINTOSH_H_RATES: McIntosh et al., J. Phys. Chem. Lett. 4, 1565 (2013), Fig. 2
(arXiv:1404.7263; 0.2 ML, from the vector graphic, converted from s^-1). This is
the rate of fcc -> hcp hopping (E_a = 95 meV, with a plateau of 1.9e-3 ps^-1
below ~120 K), i.e. the escape rate out of fcc, which Townsend's 1 / tau in hcp
matches by detailed balance. The points of the high-temperature inset repeat
those of the main panel and are omitted.
"""

